"""Phase 7 integration contracts only; none is silently enabled."""
from typing import Protocol
class LyricsTranscriber(Protocol):
    def transcribe(self,audio_path:str)->list[dict]:...
class BeatAnalyzer(Protocol):
    def analyze(self,audio_path:str)->list[int]:...
class SubjectSelector(Protocol):
    def select(self,tracks:list[dict],subject_id:str)->list[dict]:...
class StyleIllustrator(Protocol):
    def generate(self,source_frame:str,diagram:str,facts:dict)->str:...
